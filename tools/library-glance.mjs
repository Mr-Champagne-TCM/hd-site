/**
 * Writes shared/libraryGlance.mjs from the approved HD library content
 * (HD-Library-Work/content/*.json) -- a line-for-line port of the phone app's
 * tools/library-glance.py, so the shop's "Start here" one-liners are the
 * library's own words, never retyped, and the SAME words the phone prints.
 *
 *   node tools/library-glance.mjs [../HD-Library-Work]
 *
 * Re-run after any library content change. test/libraryGlance.test.mjs holds
 * the result to the phone's LibraryGlance.kt (snapshot in test/fixtures).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const LIB = join(process.argv[2] ?? join(root, "..", "HD-Library-Work"), "content");
const OUT = join(root, "shared", "libraryGlance.mjs");

// The centers' glance is CTR_LINE in the library mock (centers.json says so).
const CTR_LINE = {
  Head: "Pressure to think about questions.",
  Ajna: "How you make sense of things.",
  Throat: "How you speak and act.",
  G: "Direction, love and who you are.",
  Heart: "Willpower, promises and self-worth.",
  Spleen: "Gut instinct and health in the moment.",
  Sacral: "Life force and work energy.",
  "Solar Plexus": "Emotions, in waves.",
  Root: "Drive and pressure to get going.",
};

/** [label](#anchor) -> label; whitespace collapsed. */
const plain = (s) => s.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1").replace(/\s+/g, " ").trim();

function firstSentence(s) {
  const p = plain(s.split("\n")[0]);
  const m = /[.!?](\s|$)/.exec(p);
  return m ? p.slice(0, m.index + 1) : p;
}

const read = (f) => JSON.parse(readFileSync(join(LIB, f), "utf8"));
const centers = read("centers.json").centers;
const channels = read("channels.json").channels;
const profiles = read("profiles.json");

const block = (name, doc, obj) =>
  `/** ${doc} */\nexport const ${name} = Object.freeze(${JSON.stringify(obj, null, 2)});\n`;

const map = (o, f) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, f(v)]));

const out = [
  "// GENERATED by tools/library-glance.mjs from the approved HD library content.",
  "// Do not edit by hand: change the library, then re-run the script.",
  "// Same words as the phone app's LibraryGlance.kt (tools/library-glance.py).",
  "",
  block("CENTER_WHAT", "What each center is, in a few words (library CTR_LINE).", CTR_LINE),
  block("CENTER_DEFINED", 'First sentence of each center\'s "defined" text.', map(centers, (v) => firstSentence(v.defined))),
  block("CENTER_UNDEFINED", 'First sentence of each center\'s "undefined" text.', map(centers, (v) => firstSentence(v.undefined))),
  block("CENTER_OPEN", 'First sentence of each center\'s "open" text.', map(centers, (v) => firstSentence(v.open))),
  block("CHANNEL", 'Each channel\'s glance, keyed lower gate first ("25-51").', map(channels, (v) => plain(v.glance))),
  block("PROFILE_LINE", "Each profile line's glance, keyed by its digit.", map(profiles.lines, (v) => plain(v.glance))),
].join("\n");

writeFileSync(OUT, out, "utf8");
console.log(
  `wrote ${OUT}: ${Object.keys(centers).length} centers, ${Object.keys(channels).length} channels, ` +
    `${Object.keys(profiles.lines).length} lines`,
);
